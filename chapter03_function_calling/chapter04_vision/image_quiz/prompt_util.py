def get_multiple_choice_quiz():
    prompt = """
제공된 이미지를 보고 아래 형식의 4지 선다 퀴즈를 만들어 주세요.

조건
1. 문제는 이미지 내용을 바탕으로 작성합니다.
2. 보기는 4개를 작성합니다.
3. 정답은 반드시 하나만 존재해야 합니다.
4. 보기는 모두 자연스럽고 그럴듯하게 작성합니다.
5. 마지막에는 정답과 이유를 작성합니다.
6. Markdown 형식으로 출력합니다.

출력 형식
Q. 다음 이미지에 대한 설명 중 옳지 않은 것은 무엇인가요?

(1) ...
(2) ...
(3) ...
(4) ...

정답: (번호)

이유:
간단한 설명
"""

    return prompt.strip()
